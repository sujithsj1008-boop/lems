const fs = require("fs");
const path = require("path");

const apiBase = (process.env.LEMS_API_BASE_URL || "").trim().replace(/\/$/, "");
if (!apiBase || !/^https:\/\//i.test(apiBase)) {
    console.error("Set Netlify environment variable LEMS_API_BASE_URL to your HTTPS backend URL.");
    process.exit(1);
}

const output = `/* Generated by scripts/generate-api-config.js. Do not edit in the Netlify build output. */
window.LEMS_API_BASE_URL = ${JSON.stringify(apiBase)};
`;
fs.writeFileSync(path.join(process.cwd(), "front end", "api-base.js"), output, "utf8");
console.log("Generated frontend API configuration for the configured HTTPS backend.");
